// Reads MetaTrader 5 terminal logs on this PC and writes your gold trades for GoldTerm:
//   journal-sync.js  -> loaded by GoldTerm on startup (trades are merged into the Journal by id)
//   journal-sync.csv -> the same trades, for Journal > Import CSV or a spreadsheet
// Run:  node tools/mt5-sync.mjs        (from the xauusd-terminal folder)
// Log times are this PC's local time; account numbers are never written out.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(os.homedir(), 'AppData', 'Roaming', 'MetaQuotes', 'Terminal');
const OUT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SYMBOL = /^(XAUUSD|GOLD)\S*$/i;

function brokerName(dir) {
  try { return path.basename(fs.readFileSync(path.join(dir, 'origin.txt'), 'utf16le').replace(/^\uFEFF/, '').trim()); }
  catch { return 'MT5'; }
}
function localTime(day, hms) { // day "20261013", hms "10:15:24.226" -> epoch ms (PC local time)
  const [h, m, s] = hms.split(':');
  return new Date(+day.slice(0, 4), +day.slice(4, 6) - 1, +day.slice(6, 8), +h, +m, Math.floor(+s), Math.round((+s % 1) * 1000)).getTime();
}

const trades = [];
for (const name of fs.existsSync(ROOT) ? fs.readdirSync(ROOT) : []) {
  const dir = path.join(ROOT, name), logs = path.join(dir, 'logs');
  if (!/^[0-9A-F]{32}$/.test(name) || !fs.existsSync(logs)) continue;
  const broker = brokerName(dir);
  const open = new Map();  // position ticket -> trade
  let pending = null;      // last "market buy/sell ... sl/tp" request, attached to the next opening deal
  for (const file of fs.readdirSync(logs).filter(f => /^\d{8}\.log$/.test(f)).sort()) {
    const day = file.slice(0, 8);
    const text = fs.readFileSync(path.join(logs, file), 'utf16le').replace(/^\uFEFF/, '');
    for (const raw of text.split(/\r?\n/)) {
      const m = raw.match(/(\d\d:\d\d:\d\d\.\d+)\s+Trades\s+'\d+':\s+(.*)$/);
      if (!m) continue;
      const [, hms, msg] = m;
      let r;
      if ((r = msg.match(/^market (buy|sell) ([\d.]+) (\S+)(?: sl: ([\d.]+))?(?: tp: ([\d.]+))?$/)) && SYMBOL.test(r[3])) {
        pending = { sl: r[4] ? +r[4] : null, tp: r[5] ? +r[5] : null };
      } else if ((r = msg.match(/^modify #(\d+) (?:buy|sell) [\d.]+ (\S+) sl: ([\d.]+), tp: ([\d.]+)/)) && SYMBOL.test(r[2])) {
        const t = open.get(r[1]); if (t) { t.sl = +r[3] || null; t.tp = +r[4] || null; t.modified = true; }
      } else if ((r = msg.match(/^deal #(\d+) (buy|sell) ([\d.]+) (\S+) at ([\d.]+) done \(based on order #(\d+)\)/)) && SYMBOL.test(r[4])) {
        const [, , side, lots, , price, order] = r, ms = localTime(day, hms);
        const dir = side === 'buy' ? 'long' : 'short';
        // a deal in the opposite direction of an open position closes it (oldest first)
        const closing = [...open.values()].find(t => t.dir !== dir);
        if (closing) {
          Object.assign(closing, { status: 'closed', exit: +price, closeTime: ms });
          const s = closing.dir === 'long' ? 1 : -1;
          closing.pnl = Math.round(s * (closing.exit - closing.entry) * closing.lots * 100 * 100) / 100;
          const reason = closing.sl != null && Math.abs(closing.exit - closing.sl) < 0.06 ? 'stop loss hit'
            : closing.tp != null && Math.abs(closing.exit - closing.tp) < 0.06 ? 'take profit hit' : 'manual close';
          closing.reason = reason;
          open.delete(closing.pos);
        } else {
          const t = { id: `mt5-${order}`, pos: order, src: 'MT5', broker, dir, entry: +price, lots: +lots, openTime: ms,
                      sl: pending?.sl ?? null, tp: pending?.tp ?? null, status: 'open', tag: 'MT5', notes: broker };
          open.set(order, t); trades.push(t);
        }
        pending = null;
      }
    }
  }
}

const clean = trades.map(({ pos, modified, ...t }) => t);
fs.writeFileSync(path.join(OUT_DIR, 'journal-sync.js'),
  `// Generated by tools/mt5-sync.mjs on ${new Date().toISOString()} from MetaTrader 5 logs. Do not upload or share.\n` +
  `window.PRESET_TRADES = ${JSON.stringify(clean, null, 1)};\n`);
const cols = ['openTime', 'closeTime', 'dir', 'entry', 'sl', 'tp', 'exit', 'lots', 'pnl', 'status', 'reason', 'notes'];
fs.writeFileSync(path.join(OUT_DIR, 'journal-sync.csv'), [cols.join(',')].concat(clean.map(t => cols.map(c =>
  c.endsWith('Time') ? (t[c] ? new Date(t[c]).toISOString() : '') : (t[c] ?? '')).join(','))).join('\n'));
const closed = clean.filter(t => t.status === 'closed');
console.log(`MT5 gold trades: ${clean.length} (${closed.length} closed, ${clean.length - closed.length} open) -> journal-sync.js / journal-sync.csv`);
for (const t of clean) console.log(`  ${new Date(t.openTime).toLocaleString()}  ${t.dir.padEnd(5)} ${t.lots} @ ${t.entry}  SL ${t.sl ?? '-'}  TP ${t.tp ?? '-'}  ${t.status === 'closed' ? `exit ${t.exit} (${t.reason}) P&L ${t.pnl}` : 'OPEN'}`);
